"""
The expanded question bank, merged into the hand-written content modules.

    bank/aptitude/<topic>.json   generated by `manage.py generate_aptitude`
                                 (generators in ../generators; never edit by hand)
    bank/coding/<topic>.py       hand-written coding problems (see coding/__init__.py)

`extend_category()` appends these questions to the matching topics of a
CATEGORY dict (and adds any new coding topics), so `seed_content` and its
validation treat them exactly like the original content.
"""

import json
from pathlib import Path

APTITUDE_DIR = Path(__file__).parent / "aptitude"


def aptitude_questions(topic_slug: str) -> list[dict]:
    path = APTITUDE_DIR / f"{topic_slug}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else []


def extend_aptitude(category: dict) -> None:
    for topic in category["topics"]:
        topic["questions"] = topic["questions"] + aptitude_questions(topic["slug"])


def extend_coding(category: dict) -> None:
    from .coding import NEW_TOPICS, questions_for

    existing = {t["slug"] for t in category["topics"]}
    for topic in category["topics"]:
        topic["questions"] = topic["questions"] + questions_for(topic["slug"])
    for topic in NEW_TOPICS:
        if topic["slug"] not in existing:
            category["topics"].append({**topic, "questions": questions_for(topic["slug"])})
